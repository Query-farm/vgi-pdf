"""Generate an invented two-page invoice with a deliberate stale-amount variant."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from reportlab.lib import colors
from reportlab.pdfgen import canvas


def main():
    """Write deterministic demonstration PDF bytes and explicit provenance."""
    folder = Path(__file__).resolve().parent / "fixtures"
    folder.mkdir(exist_ok=True)
    path = folder / "invoice_variants.pdf"
    pdf = canvas.Canvas(str(path), pagesize=(612, 792), invariant=True)
    pdf.setTitle("Synthetic invoice arithmetic variants")
    pdf.setAuthor("Query.Farm notebook fixture")
    items = [
        ("TAPE", 10, "12.50", "125.00"),
        ("BOXES", 4, "20.00", "80.00"),
        ("GLOVES", 3, "15.00", "45.00"),
        ("LABELS", 8, "2.50", "20.00"),
        ("FOAM", 6, "7.50", "45.00"),
    ]
    for page in (1, 2):
        pdf.setFillColor(colors.HexColor("#243e32"))
        pdf.setFont("Helvetica-Bold", 20)
        pdf.drawString(54, 730, "Synthetic invoice arithmetic")
        pdf.setFont("Helvetica", 10)
        pdf.setFillColor(colors.HexColor("#526b5b"))
        pdf.drawString(54, 707, f"Variant {page} | invented values | USD | not a real transaction")
        note = (
            "Baseline: printed quantities and amounts agree."
            if page == 1
            else "Quantity changed; printed line amount and total intentionally left stale."
        )
        pdf.drawString(54, 688, note)
        xs = [54, 240, 310, 415, 558]
        ys = [632 - 32 * i for i in range(8)]
        pdf.setStrokeColor(colors.HexColor("#72877b"))
        pdf.setLineWidth(0.7)
        for x in xs:
            pdf.line(x, ys[-1], x, ys[0])
        for y in ys:
            pdf.line(xs[0], y, xs[-1], y)
        rows = [["SKU", "Qty", "Unit", "Amount"]]
        for sku, qty, unit, amount in items:
            rows.append([sku, str(12 if page == 2 and sku == "TAPE" else qty), unit, amount])
        rows.append(["TOTAL", "", "", "315.00"])
        for r, row in enumerate(rows):
            pdf.setFillColor(colors.HexColor("#243e32"))
            pdf.setFont("Helvetica-Bold" if r in (0, 6) else "Helvetica", 11)
            for col, value in enumerate(row):
                pdf.drawString(xs[col] + 10, ys[r] - 21, value)
        pdf.setFont("Helvetica", 9)
        pdf.setFillColor(colors.HexColor("#526b5b"))
        pdf.drawString(54, 360, "No taxes, shipping, discounts or currency conversion in this fixture.")
        pdf.showPage()
    pdf.save()
    provenance = {
        "source": (
            "Entirely invented invoice content generated by generate_fixture.py with ReportLab 5.1.0. "
            "No real transaction or customer data."
        ),
        "file": path.name,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "page_units": "612x792 PDF points; US Letter",
        "currency": "USD demonstration values",
        "variants": {
            "1": "Five line items; printed and computed total 315.00.",
            "2": (
                "TAPE quantity changes 10 to 12; printed amount 125.00 and total 315.00 intentionally stale; "
                "computed total 340.00."
            ),
        },
        "pdf_metadata_time": (
            "Deterministic ReportLab invariant timestamp; not an observed creation or transaction date."
        ),
    }
    (folder / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


if __name__ == "__main__":
    main()
