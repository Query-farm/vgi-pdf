"""Create one intentionally encrypted demonstration input, never decrypt it in examples.

Run with the released worker environment, which already supplies pikepdf. Encryption
uses fresh random material, so regenerated bytes can differ. Commit the resulting
file and its recorded hash together; notebook runs use the committed bytes only.
The public example password protects no private data and is not used by the notebook.
"""

from pathlib import Path

import pikepdf

folder = Path(__file__).parent / "fixtures"
with pikepdf.Pdf.open(folder / "meta.pdf") as pdf:
    pdf.save(
        folder / "encrypted.pdf",
        encryption=pikepdf.Encryption(user="public-notebook-example", owner="public-notebook-owner", R=6),
    )
